import { readFile, writeFile } from 'node:fs/promises';
import { gzipSync } from 'node:zlib';

const entries = [['/', 'index.html', 'text/html; charset=utf-8'], ['/styles.css', 'styles.css', 'text/css; charset=utf-8'], ['/app.js', 'app.js', 'text/javascript; charset=utf-8'], ['/model.js', 'model.js', 'text/javascript; charset=utf-8'], ['/frame-stream.js', 'frame-stream.js', 'text/javascript; charset=utf-8']];
entries.push(['/camera-view.js', 'camera-view.js', 'text/javascript; charset=utf-8']);
entries.push(['/wifi-settings.js', 'wifi-settings.js', 'text/javascript; charset=utf-8']);
entries.push(['/wifi-scan.js', 'wifi-scan.js', 'text/javascript; charset=utf-8']);
entries.push(['/device-network.js', 'device-network.js', 'text/javascript; charset=utf-8']);
let source = '// Generated by Web source embed-web.mjs. No network credentials.\n#pragma once\n#include <Arduino.h>\nstruct WebAsset { const char *uri; const char *type; const uint8_t *data; size_t size; };\n';
for (const [index, [, file]] of entries.entries()) {
  const data = gzipSync(await readFile(new URL(file, import.meta.url)), { level: 9 });
  source += `static const uint8_t web_${index}[] PROGMEM = {\n`;
  for (let i = 0; i < data.length; i += 24) source += [...data.subarray(i, i + 24)].join(',') + ',\n';
  source += '};\n';
  console.log(`${file}: ${data.length} compressed bytes`);
}
source += 'static const WebAsset webAssets[] = {\n';
entries.forEach(([uri, , type], index) => { source += `{"${uri}","${type}",web_${index},sizeof(web_${index})},\n`; });
source += '};\n';
await writeFile(new URL('../主控板源码/CatCameraControl/web_assets.h', import.meta.url), source);

